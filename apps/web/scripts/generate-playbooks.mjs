// Bundle the incident playbooks (lib/server/playbooks/*.md) into a TypeScript
// module so the system prompt never reads the filesystem at runtime.
//   pnpm --filter @neo/web playbooks:generate
// test/playbooks.test.ts fails when generated.ts is out of date.
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const dir = path.join(here, "../lib/server/playbooks");
// Keep in sync with PLAYBOOK_IDS in lib/playbooks.ts (the test checks this too).
const IDS = ["clicked_link", "entered_password", "sent_gift_cards", "shared_code", "paid_scammer", "device_compromised"];

export function renderGenerated(readFile = (id) => readFileSync(path.join(dir, `${id}.md`), "utf8")) {
  const entries = IDS.map((id) => `  ${id}: ${JSON.stringify(readFile(id).replace(/\r\n?/g, "\n").trimEnd() + "\n")},`);
  return [
    "// GENERATED by scripts/generate-playbooks.mjs from lib/server/playbooks/*.md. Do not edit by hand.",
    "export const PLAYBOOK_MARKDOWN = {",
    ...entries,
    "} as const;",
    "",
  ].join("\n");
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  writeFileSync(path.join(dir, "generated.ts"), renderGenerated());
  console.log(`Wrote ${IDS.length} playbooks to lib/server/playbooks/generated.ts`);
}
