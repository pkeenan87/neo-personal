// Writes the cross-language policy test vector the Rust verifier is tested against
// (apps/desktop/crates/agent-core/tests/fixtures/policy-vector.json).
//
// The canonical strings and the signature come from the TypeScript side (`canonicalJson` in
// `@neo/verdict`, the same function the server signs with) using a THROWAWAY P-256 key made here.
// Only the public JWK is written; the private key is never stored, so re-running makes a new vector.
//
//   pnpm --filter @neo/verdict build
//   node apps/desktop/ci/gen-policy-vector.mjs
import { createHash, generateKeyPairSync, sign } from "node:crypto";
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { base64urlEncode, canonicalJson, policyVersionBody } from "../../../packages/verdict/dist/index.js";

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, "../crates/agent-core/tests/fixtures/policy-vector.json");

// ---- Canonical JSON cases: the value, and what `canonicalJson` makes of it. -----------------------
const caseValues = [
  { name: "sorted keys, nesting and null", value: { b: 1, a: [3, 1, 2], c: { z: true, y: null, x: {} }, d: [] } },
  { name: "quote, backslash, control characters", value: { q: 'a"b\\c', ctl: "x\u0000y\u0007z\u001f\b\f\n\r\t" } },
  { name: "non-ASCII is kept as UTF-8", value: { name: "Zoë ☃ \u{1F600}", slash: "a/b", sep: "  ", del: "\u007f" } },
  { name: "key order is UTF-16 code units", value: { "\u{1F600}": 1, "～": 2, Z: 3, a: 4, "é": 5, "": 6 } },
  { name: "integers and booleans", value: { zero: 0, neg: -7, big: 9007199254740991, t: true, f: false } },
];
const canonicalCases = caseValues.map(({ name, value }) => ({ name, value, canonical: canonicalJson(value) }));

// ---- A compiled-shape bundle with awkward text, signed with the throwaway key. ----------------------
const body = {
  v: 1,
  deviceId: "11111111-1111-4111-8111-111111111111",
  memberId: "22222222-2222-4222-8222-222222222222",
  timeZone: "America/New_York",
  mode: "child",
  web: { categories: ["adult", "gambling"], safeSearch: true, youtubeRestricted: "moderate", allow: [], block: ["bad.example"] },
  apps: {
    block: [{ bundleId: "com.roblox.Roblox" }, { signer: 'Roblox "Corp" é', image: "RobloxPlayerBeta.exe" }],
    requireApproval: true,
    approved: [{ signer: "Mozilla Corporation", image: "firefox.exe" }],
  },
  screenTime: {
    dailyMinutes: { mon: 120, tue: 120, wed: 120, thu: 120, fri: 120, sat: 180, sun: null },
    downtime: [{ start: "21:00", end: "07:00" }],
    warnMinutes: 10,
    allowDuringDowntime: [{ bundleId: "us.zoom.xos" }],
    grants: [{ minutes: 30, until: "2026-11-03T05:00:00.000Z" }],
  },
};
const policyVersion = createHash("sha256").update(policyVersionBody(body), "utf8").digest("hex");
const bundle = { ...body, policyVersion, issuedAt: "2026-11-02T12:00:00.000Z", expiresAt: "2026-11-09T12:00:00.000Z" };
const canonicalBundle = canonicalJson(bundle);

const { privateKey, publicKey } = generateKeyPairSync("ec", { namedCurve: "P-256" });
const jwk = { ...publicKey.export({ format: "jwk" }), kid: "test-vector-key", alg: "ES256", use: "sig" };
const sig = base64urlEncode(sign("sha256", Buffer.from(canonicalBundle, "utf8"), { key: privateKey, dsaEncoding: "ieee-p1363" }));
const envelope = { bundle, sig, keyId: jwk.kid, alg: "ES256" };

writeFileSync(
  out,
  `${JSON.stringify({ note: "Generated by apps/desktop/ci/gen-policy-vector.mjs with a throwaway key. Do not edit.", canonicalCases, jwk, envelope, canonicalBundle, policyVersionBody: policyVersionBody(body) }, null, 2)}\n`,
);
console.log(`wrote ${out}`);
